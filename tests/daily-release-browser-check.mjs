import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {browserOptions} from './browser-runtime.mjs';
import course from '../courses/alice-python/index.mjs';
import {createEngine} from '../shared/engine-core.mjs';
import {createGuildServer} from '../server.mjs';

const require = createRequire(import.meta.url), {chromium} = require('playwright');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'guild-daily-browser-'));
const engine = createEngine(course), state = engine.initialState();
engine.importCourseHistory(state, {awardRewards: false});
for (const key of ['currency', 'gold', 'books', 'petals', 'crystals']) state[key] = 0;
for (const key of Object.keys(state.materials)) state.materials[key] = 0;
const stateFile = path.join(directory, 'progress.json');
fs.writeFileSync(stateFile, JSON.stringify(state));
const server = createGuildServer({course, stateFile, profileId: 'daily-browser', importHistory: false, reviewProvider: 'off', learningProvider: 'off', sharedReviewProvider: 'off'});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch(browserOptions());
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}}), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(12000);
  await page.goto(origin + '/#book');
  await page.locator('[data-book-section="daily"]').click();
  const book = page.locator('[data-book-point="daily-point"]');
  assert.match(await book.textContent(), /Сегодня доступно/);
  assert.match(await book.textContent(), /60/);
  await book.locator('[data-book-open-point]').click();
  const frame = page.frameLocator('iframe');
  await frame.locator('.wb-brand h1').filter({hasText: 'Ежедневное повторение'}).waitFor();
  assert.equal(await frame.locator('.wb-outline-practice').count(), 1);
  assert.equal(await frame.locator('.wb-outline-theory').count(), 1);
  await frame.locator('[data-workspace-node="daily"]').click();
  const field = frame.locator('[data-cell-code="daily"]');
  await field.fill('clean_name = raw_name.strip().lower()\nprint(clean_name)');
  const resultPromise = page.waitForResponse(response => response.url().endsWith('/api/check'));
  await frame.locator('[data-action="cell-check"]').click();
  const passed = await (await resultPromise).json();
  assert.equal(passed.result.ok, true);
  assert.equal(passed.state.currency, 60);
  await frame.locator('.nb-test-tab.passed').first().waitFor();
  assert.equal(await frame.locator('.nb-test-tab.passed').count(), 4);
  await page.goto(origin + '/#world');
  await page.locator('[data-world-point="daily-point"]').click();
  const drawer = page.locator('[data-world-drawer]');
  assert.match(await drawer.textContent(), /На сегодня выполнено/);
  assert.match(await drawer.locator('[data-world-open]').textContent(), /Повторить без награды/);
  assert.match(await drawer.locator('.world-detail-note').textContent(), /завтра/);
  assert.doesNotMatch(await drawer.textContent(), /40 минут|Статуя активируется/);
  await page.mouse.move(100, 100);
  await page.waitForTimeout(350);
  await page.screenshot({path: '/private/tmp/guild-daily-ready.png', fullPage: false});
  assert.deepEqual(errors, []);
  console.log('Daily book → own lesson → four green tests → dated payout → correct map status: OK');
} finally {
  await browser.close();
  await new Promise(resolve => {server.close(resolve); server.closeIdleConnections?.();});
  fs.rmSync(directory, {recursive: true, force: true});
}
