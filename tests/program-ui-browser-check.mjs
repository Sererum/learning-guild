import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createGuildServer} from '../server.mjs';
import {writeSyntheticCourseProfile} from './course-profile-fixture.mjs';
import {adaptationFixtureProvider} from './adaptation-fixtures.mjs';
import {browserOptions} from './browser-runtime.mjs';
const {chromium}=createRequire(import.meta.url)('playwright');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'guild-program-ui-')),file=path.join(directory,'progress.json');
writeSyntheticCourseProfile(file);
const server=createGuildServer({stateFile:file,reviewProvider:'off',learningProvider:'file',learningFixtureProvider:adaptationFixtureProvider,sharedReviewProvider:'off'});
let browser;
try{
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));browser=await chromium.launch(browserOptions());
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],failed=[];
 page.on('pageerror',error=>errors.push(error.message));page.on('response',response=>{if(response.status()>=400)failed.push(response.status()+' '+new URL(response.url()).pathname);});
 const origin='http://127.0.0.1:'+server.address().port,state=async()=>fetch(origin+'/api/state').then(r=>r.json());
 await page.goto(origin+'/#wishes');await page.locator('[data-stellar-banner="weapon"]').click();
 assert.match(await page.locator('.stellar-page').innerText(),/Клинок лунного архива/);
 await page.locator('[data-resource-guide]').first().click();await page.locator('.resource-guide-dialog').waitFor();
 assert.match(await page.locator('.resource-guide-dialog').innerText(),/Мора: \+400/);
 assert.match(await page.locator('.resource-guide-dialog').innerText(),/Книги опыта: \+1/);
 await page.locator('[data-resource-lesson]').first().click();await page.frameLocator('iframe').locator('.workbench').waitFor();
 await page.locator('[data-page="settings"]').click();await page.locator('[data-settings-tab="generation"]').click();
 assert.equal(await page.locator('[data-ai-policy] select').count(),7);assert.equal(await page.locator('[data-ai-policy] select[name=lessonGeneration]').inputValue(),'xhigh');assert.equal(await page.locator('[data-ai-policy] select[name=tutorHint]').inputValue(),'medium');
 await page.screenshot({path:'/private/tmp/guild-ai-policy-settings.png',fullPage:true});
 await page.locator('[data-page="program"]').click();await page.getByText('Дополнительная практика по готовому уроку',{exact:true}).click();await page.locator('[data-program-form]').waitFor();
 await page.locator('[data-program-form] select[name="lessonId"]').selectOption('algorithms');
 await page.locator('[data-program-form] textarea').fill('Хочу сначала простой пример на маленьких числах, затем короткую самостоятельную практику.');
 await page.screenshot({path:'/private/tmp/guild-program-request.png',fullPage:true});
 const before=(await state()).state;
 await page.locator('[data-program-form] textarea').press('Enter');await page.locator('[data-program-consent]').waitFor({timeout:10000});
 assert.equal(await page.locator('[data-program-consent] input:checked').count(),0);
 await page.locator('[data-program-decline]').click();await page.locator('[data-program-open]').waitFor({timeout:60000});
 assert.match(await page.locator('.program-job').innerText(),/Исходный урок и его результаты сохранены/);
 await page.screenshot({path:'/private/tmp/guild-program-ready.png',fullPage:true});
 const after=await state();for(const key of ['currency','gold','books','claims','courseCredits'])assert.deepEqual(after.state[key],before[key],key+' preserved');
 assert.equal(after.learning.jobs[0].effort,'xhigh');assert.equal(after.learning.jobs[0].branches.length,1);assert.equal(after.learning.jobs[0].branches[0].kind,'reinforcement');
 await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'/private/tmp/guild-program-mobile.png',fullPage:true});
 await page.locator('[data-program-open]').click();await page.frameLocator('iframe').locator('.workbench').waitFor();
 assert.deepEqual(errors,[]);assert.deepEqual(failed,[]);
 console.log('Weapon banner → resource guide → lesson; visible effort policy; program request by Enter → consent decline → validated optional branch → open lesson; mobile, no awards and no browser errors: OK');
}finally{await browser?.close();await new Promise(resolve=>{server.close(resolve);server.closeIdleConnections?.();});fs.rmSync(directory,{recursive:true,force:true});}
