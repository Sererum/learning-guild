import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {createLocalCourseStore} from '../local-courses.mjs';
import {createAccountServer} from '../account-server.mjs';
import {browserOptions} from './browser-runtime.mjs';
const {chromium}=createRequire(import.meta.url)('playwright');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'guild-atlas-browser-'));
const store=createLocalCourseStore({root});
store.create({id:'synthetic',title:'Учебное путешествие',learnerName:'Ученик',goal:'Пройти учебный маршрут',contentMode:'blank',preferencesMode:'new'});
const server=createAccountServer({root,python:process.env.GUILD_PYTHON||'python3.12',reviewProvider:'off',learningProvider:'off'});
let browser;
try{
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const base='http://127.0.0.1:'+server.address().port;
 browser=await chromium.launch(browserOptions());
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('response',response=>{if(response.status()>=400)errors.push(response.status()+' '+response.url());});
 // Neutral rendered snapshot only. No real course or learner data is used.
 const blocks=Array.from({length:10},(_,i)=>({id:'b'+i,title:'Блок '+(i+1)}));
 const nodes=blocks.flatMap((b,i)=>Array.from({length:3},(_,j)=>({id:`n${i}-${j}`,blockId:b.id,title:`${i+1}.${j+1} · Учебная тема`,main:true,status:i===0&&j===0?'done':i===0?'ready':'future',completed:i===0&&j===0,available:i===0,prerequisites:[],lessonPlan:['Рассмотрим понятный пример. Проследим каждый шаг.','Потренируем новый приём. Сравним результаты на разных данных.'],materials:[]})));
 await page.route('**/api/state?**',async route=>{const response=await route.fetch(),data=await response.json();data.program={...data.program,blocks,nodes,nextId:'n0-1'};await route.fulfill({response,json:data});});
 await page.goto(base+'/?account=synthetic#world');
 const canvas=page.locator('.world-canvas');await canvas.waitFor();
 await page.waitForFunction(()=>{const img=document.querySelector('.world-map-image');return img?.complete&&img.naturalWidth===2702;});
 assert.equal(await page.locator('[data-world-point]').count(),24);
 assert.equal(await page.locator('[data-world-slot]').count(),72);
 const transform=()=>canvas.evaluate(el=>el.style.transform);
 const before=await transform();
 await page.locator('[data-world-point="n0-1"]').click();
 assert.equal(await transform(),before);
 await page.getByRole('heading',{name:'1.2 · Учебная тема',exact:true}).waitFor();
 await page.screenshot({path:path.join(os.tmpdir(),'guild-teyvat-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Закрыть описание',exact:true}).click();
 await page.locator('[data-world-pass]').selectOption('1');
 assert.equal(await page.locator('[data-world-point]').count(),6);
 await page.locator('[data-world-pass]').selectOption('0');
 assert.equal(await transform(),before);
 const box=await page.locator('.world-viewport').boundingBox();
 await page.mouse.move(box.x+box.width*.25,box.y+box.height*.7);await page.mouse.down();await page.mouse.move(box.x+box.width*.25+90,box.y+box.height*.7+40,{steps:8});await page.mouse.up();
 assert.notEqual(await transform(),before);
 await page.getByRole('button',{name:'Показать весь Тейват',exact:true}).click();
 await page.screenshot({path:path.join(os.tmpdir(),'guild-teyvat-overview.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-world-current]').click();
 await page.locator('[data-world-point="n0-1"]').click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 const drawer=await page.locator('.world-quest-drawer').boundingBox();assert.ok(drawer.x>=0&&drawer.x+drawer.width<=390);
 await page.screenshot({path:path.join(os.tmpdir(),'guild-teyvat-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Atlas browser checks passed: real asset, selection, pass cameras, pan, overview, responsive drawer, no network or JS errors.');
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));fs.rmSync(root,{recursive:true,force:true});}
