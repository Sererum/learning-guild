import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {createAccountServer} from '../account-server.mjs';
import {createLocalCourseStore} from '../local-courses.mjs';
import {learningCourseFixture} from './learning-course-fixture.mjs';
import {browserOptions} from './browser-runtime.mjs';
const {chromium}=createRequire(import.meta.url)('playwright');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'guild-daily-browser-'));
const course=learningCourseFixture();
course.presentation={points:{'source-point':{phase:'mastered',available:true}}};
course.program={blocks:[{id:'first',title:'Пройденная тема',nodeIds:['source-topic']},{id:'second',title:'Следующий блок',nodeIds:['next-topic']}]};
course.daily={timeZone:'Europe/Moscow',reward:{gems:60,gold:100,books:1,materials:{ore:2}},variants:[{id:'synthetic-copy',topicId:'source-topic',title:'Техническая проверка результата',prompt:'value — число. Сохрани его в answer и выведи answer. Это временная техническая проверка интерфейса.',starter:'value = 3\n# Напиши свой код здесь',reviewed:true,tests:[{label:'Положительное число',inputs:{value:3},expected:{answer:3}},{label:'Другой вход',hidden:true,inputs:{value:-2},expected:{answer:-2}}]}]};
let now=new Date('2026-10-22T12:00:00Z');
const store=createLocalCourseStore({root:directory});
store.create({id:'synthetic',title:'Тестовый курс',learnerName:'Ученик',goal:'Тест интерфейса',contentMode:'blank',preferencesMode:'new'});
const courseDir=path.join(store.coursesRoot,'synthetic');
fs.mkdirSync(path.join(courseDir,'profile'),{recursive:true});
fs.writeFileSync(path.join(courseDir,'content.json'),JSON.stringify(course));
fs.writeFileSync(path.join(courseDir,'program.json'),JSON.stringify({...course.program,roadmap:course.adaptation.roadmap}));
const server=createAccountServer({root:directory,python:process.env.GUILD_PYTHON||'python3.12',importHistory:false,reviewProvider:'off',learningProvider:'off',dailyClock:()=>now});
let browser;
try{
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const base='http://127.0.0.1:'+server.address().port;
 const state=async()=>await(await fetch(base+'/api/state?account=synthetic')).json();
 browser=await chromium.launch(browserOptions());
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));page.setDefaultTimeout(15000);
 await page.goto(base+'/?account=synthetic#world');await page.locator('.world-canvas').waitFor();
 assert.equal(await page.locator('.world-landmark .map-icon-statue').count(),2);
 assert.equal(await page.locator('.world-landmark.is-active .map-icon-statue').count(),1);
 assert.equal(await page.locator('[data-world-point="source-topic"] .map-icon-teleport [fill="#83e8ff"]').count(),1);
 assert.equal(await page.locator('[data-world-select="atlas-statue:second"] .map-icon-statue [fill="#969ea3"]').count(),1);
 assert.equal(await page.locator('.world-daily-marker').count(),1);
 await page.screenshot({path:path.join(os.tmpdir(),'guild-daily-world-desktop.png'),fullPage:true});
 await page.locator('.world-map-toolbar [data-world-daily]').click();await page.locator('#daily-code').waitFor();
 assert.match(page.url(),/#daily$/);
 const baseline=(await state()).state.currency;
 const draft='value = 3\nanswer = value\nprint(answer)';
 await page.locator('#daily-code').fill(draft);
 const editorHandle=await page.locator('#daily-code').elementHandle();
 await page.waitForTimeout(1200);
 assert.equal(await editorHandle.evaluate(el=>el===document.querySelector('#daily-code')&&el===document.activeElement),true,'countdown does not replace editor or steal focus');
 await page.locator('[data-daily-action="run"]').click();await page.locator('[data-daily-result] pre').waitFor();
 assert.equal((await state()).state.currency,baseline);
 await page.locator('[data-daily-action="check"]').click();await page.locator('[data-daily-action="claim"]').waitFor();
 assert.equal((await state()).state.currency,baseline,'checking does not grant reward');
 assert.equal(await page.locator('#daily-code').inputValue(),draft);
 await page.screenshot({path:path.join(os.tmpdir(),'guild-daily-completed-desktop.png'),fullPage:true});
 await page.locator('[data-daily-action="claim"]').click();await page.locator('.is-claimed').waitFor();
 assert.equal((await state()).state.currency,baseline+60);
 assert.equal(await page.locator('[data-daily-action="claim"]').count(),0);
 await page.reload();await page.locator('.is-claimed').waitFor();assert.equal((await state()).state.currency,baseline+60);
 await page.locator('[data-page="book"]').click();await page.locator('[data-book-section="daily"]').click();await page.locator('#daily-code').waitFor();
 assert.equal(await page.locator('.book-card').count(),0,'book daily hides legacy reward tasks');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:path.join(os.tmpdir(),'guild-daily-mobile.png'),fullPage:true});
 // A stale page must refresh after the server rejects yesterday's ID, preserving its local draft.
 const oldId=(await state()).daily.today.id;now=new Date('2026-10-23T12:00:00Z');
 await page.locator('#daily-code').fill(draft+'\n# Сохраняем старый черновик');
 await page.locator('[data-daily-action="check"]').click();
 await page.waitForFunction(()=>document.querySelector('.daily-task .eyebrow')?.textContent==='2026-10-23');
 assert.equal(await page.evaluate(id=>window.guildStorage.getItem('daily-draft:'+id),oldId),draft+'\n# Сохраняем старый черновик');
 // Timer refreshes exactly once at the deadline rather than rerendering every tick.
 now=new Date('2026-10-23T20:59:58Z');await page.goto(base+'/?account=synthetic#daily');await page.reload();await page.locator('[data-daily-countdown]').waitFor();
 let refreshes=0;page.on('request',req=>{if(req.url().includes('/api/state'))refreshes++;});
 now=new Date('2026-10-23T21:00:01Z');
 await page.waitForFunction(()=>document.querySelector('.daily-task .eyebrow')?.textContent==='2026-10-24');
 await page.waitForTimeout(2200);assert.equal(refreshes,1);
 assert.deepEqual(errors,[]);
 console.log('Daily browser checks passed: map states and marker, book navigation, run/check/claim, reward once, drafts, stale rejection, one expiry refresh, mobile, no JS errors.');
 console.log('Screenshots: '+['guild-daily-world-desktop.png','guild-daily-completed-desktop.png','guild-daily-mobile.png'].map(name=>path.join(os.tmpdir(),name)).join(', '));
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));fs.rmSync(directory,{recursive:true,force:true});}
